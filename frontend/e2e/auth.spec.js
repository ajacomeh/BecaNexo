import { randomUUID } from 'node:crypto'
import { test, expect } from '@playwright/test'

test('registro, login, restauración y logout contra Django real', async ({ page }, testInfo) => {
  // Crea exclusivamente una cuenta desechable nueva. No toca cuentas existentes.
  const email = `e2e-${randomUUID()}@example.com`
  const password = `Prueba!${randomUUID()}`
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/inicio')
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('login-desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'Crear una cuenta' }).click()
  await expect(page.getByRole('heading', { name: 'Crea tu cuenta' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('registro-desktop.png'), fullPage: true })
  await page.getByLabel('Nombre completo').fill('Verificación desechable')
  await page.getByLabel('Correo electrónico').fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  await page.getByLabel('Confirmar contraseña').fill(password)
  const registration = page.waitForResponse((response) => response.url().endsWith('/api/auth/registro/'))
  await page.getByRole('button', { name: 'Crear mi cuenta' }).click()
  expect((await registration).status()).toBe(201)
  await expect(page.getByText('Tu cuenta fue creada. Ya puedes iniciar sesión.')).toBeVisible()
  await page.getByLabel('Correo electrónico').fill(email.toUpperCase())
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  const loginResponse = page.waitForResponse((response) => response.url().endsWith('/api/auth/login/'))
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  const result = await loginResponse
  expect(result.status()).toBe(200)
  expect((await result.request().allHeaders()).origin).toBe('http://127.0.0.1:5173')
  await expect(page.getByRole('heading', { name: 'Hola, Verificación desechable' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Hola, Verificación desechable' })).toBeVisible()
  await expect(page.getByText('postulante', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('inicio-mobile.png'), fullPage: true })
  const logoutResponse = page.waitForResponse((response) => response.url().endsWith('/api/auth/logout/'))
  await page.getByRole('button', { name: 'Cerrar sesión' }).click()
  expect((await logoutResponse).status()).toBe(204)
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible()
  await page.goto('/inicio')
  await expect(page).toHaveURL(/\/login$/)
  await page.screenshot({ path: testInfo.outputPath('login-mobile.png'), fullPage: true })
  await page.getByRole('link', { name: 'Crear una cuenta' }).click()
  await expect(page.getByLabel('Nombre completo')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('registro-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(await page.evaluate(() => localStorage.length + sessionStorage.length)).toBe(0)
})
