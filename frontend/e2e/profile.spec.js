import { randomUUID } from 'node:crypto'
import { test, expect } from '@playwright/test'

test('perfil progresivo y preferencias persisten en Django', async ({ page }, testInfo) => {
  const email = `perfil-e2e-${randomUUID()}@example.com`
  const password = `Prueba!${randomUUID()}`
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/registro')
  await page.getByLabel('Nombre completo').fill('Perfil desechable')
  await page.getByLabel('Correo electrónico').fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  await page.getByLabel('Confirmar contraseña').fill(password)
  await page.getByRole('button', { name: 'Crear mi cuenta' }).click()
  await expect(page.getByText('Tu cuenta fue creada. Ya puedes iniciar sesión.')).toBeVisible()
  await page.getByLabel('Correo electrónico').fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await page.getByRole('link', { name: 'Completar mi perfil' }).click()
  await page.getByLabel('País de residencia').selectOption({ label: 'España' })
  await page.getByLabel('Ciudad de residencia').fill('Ciudad de prueba')
  await page.getByRole('button', { name: 'Guardar datos personales' }).click()
  await expect(page.getByText('Cambios guardados.')).toBeVisible()
  await page.getByRole('button', { name: 'Añadir formación' }).click()
  await page.getByLabel('Nivel académico').selectOption('grado')
  await page.getByLabel('Estado de estudios').selectOption('concluidos')
  await page.getByLabel('Carrera / programa').fill('Formación de prueba')
  await page.getByLabel('¿Título obtenido?').selectOption('true')
  await page.getByLabel('Fecha de finalización').fill('2022-06-01')
  await page.getByLabel('Promedio obtenido').fill('8.5')
  await page.getByLabel('Mínimo de la escala').fill('0')
  await page.getByLabel('Máximo de la escala').fill('10')
  await page.getByRole('button', { name: 'Guardar formación' }).click()
  await expect(page.getByText('Formación de prueba · Concluidos')).toBeVisible()
  await page.getByRole('button', { name: /Editar formación:/ }).click()
  await page.getByLabel('Carrera / programa').fill('Formación editada')
  await page.getByRole('button', { name: 'Guardar formación' }).click()
  await expect(page.getByText('Formación editada · Concluidos')).toBeVisible()
  await page.getByRole('button', { name: 'Añadir experiencia' }).click()
  await page.getByLabel('Cargo / actividad').fill('Actividad desechable')
  await page.getByLabel('Fecha de inicio').fill('2023-01-01')
  await page.getByLabel('¿Continúa actualmente?').selectOption('true')
  await page.getByRole('button', { name: 'Guardar experiencia' }).click()
  await expect(page.getByText(/Actividad desechable · 2023/)).toBeVisible()
  await page.getByRole('button', { name: /Eliminar experiencia:/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByText(/Actividad desechable · 2023/)).toBeVisible()
  await page.getByRole('button', { name: /Eliminar experiencia:/ }).click()
  await page.getByRole('button', { name: 'Confirmar eliminación' }).click()
  await expect(page.getByText('Registro eliminado.')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Ciudad de residencia')).toHaveValue('Ciudad de prueba')
  await expect(page.getByText('Formación editada · Concluidos')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('perfil-desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'Ir a idiomas y preferencias' }).click()
  await page.getByRole('button', { name: 'Añadir idioma' }).click()
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption({ label: 'Inglés' })
  await page.getByLabel('Nivel declarado (MCER)').selectOption('B2')
  await page.getByRole('button', { name: 'Guardar idioma' }).click()
  await expect(page.getByText('Inglés · B2')).toBeVisible()
  await page.getByRole('button', { name: 'Añadir preferencia' }).click()
  await page.getByLabel('Nivel deseado').selectOption('maestria')
  await page.getByLabel('Modalidad deseada').selectOption('virtual')
  await page.getByRole('button', { name: 'Guardar preferencia' }).click()
  await expect(page.getByText('Maestría · Virtual')).toBeVisible()
  await page.getByRole('button', { name: 'Añadir destino' }).click()
  await page.getByLabel('País de destino').selectOption({ label: 'Ecuador' })
  await page.getByRole('button', { name: 'Guardar destino' }).click()
  await page.getByRole('button', { name: 'Añadir área' }).click()
  await page.getByLabel('Área de interés').selectOption({ label: 'Educación' })
  await page.getByRole('button', { name: 'Guardar área' }).click()
  await page.getByLabel('¿Puedes trasladarte?').selectOption('false')
  await page.getByLabel('¿Puedes estudiar en el extranjero?').selectOption('')
  await page.getByRole('button', { name: 'Guardar disponibilidad' }).click()
  await expect(page.getByRole('button', { name: 'Guardar disponibilidad' })).toBeEnabled()
  await page.reload()
  await expect(page.getByText('Inglés · B2')).toBeVisible()
  await expect(page.getByText('Maestría · Virtual')).toBeVisible()
  await expect(page.getByLabel('¿Puedes trasladarte?')).toHaveValue('false')
  await expect(page.getByLabel('¿Puedes estudiar en el extranjero?')).toHaveValue('')
  await page.screenshot({ path: testInfo.outputPath('preferencias-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('preferencias-mobile.png'), fullPage: true })
  await page.getByRole('link', { name: 'Volver a formación' }).click()
  await expect(page.getByLabel('Ciudad de residencia')).toHaveValue('Ciudad de prueba')
  await page.screenshot({ path: testInfo.outputPath('perfil-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Cerrar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Inicia sesión' })).toBeVisible()
})
